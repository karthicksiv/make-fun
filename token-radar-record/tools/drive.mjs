// QA only: drive the page with the keyboard and the mouse and assert what it shows.
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
const { chromium } = createRequire(import.meta.url)('playwright');
const browser = await chromium.launch(), page = await browser.newPage({ viewport: { width: 1152, height: 720 } });
const errors = []; page.on('pageerror', (e) => errors.push(e.message));
await page.goto(pathToFileURL(process.argv[2]).href); await page.waitForSelector('#rows table');
const check = (name, ok, got) => console.log((ok ? 'PASS ' : 'FAIL ') + name + (ok ? '' : ` (got ${JSON.stringify(got)})`));
const text = (sel) => page.locator(sel).first().innerText();
const rows = () => page.locator('#rows tbody tr[data-open]').count();
check('board lists every ranked protocol', (await rows()) === 198, await rows());
await page.keyboard.press('j'); await page.keyboard.press('j'); await page.keyboard.press('k');
check('j/k move the cursor', (await page.locator('tr.cur td').first().innerText()).split('\n')[0] === '2', await page.locator('tr.cur td').first().innerText());
await page.keyboard.press('Enter');
check('enter opens the cursor row', (await text('.detail h2')) === 'Sentora Curator', await text('.detail h2'));
check('detail lists six costed steps', (await page.locator('.steps tbody tr').count()) === 7, await page.locator('.steps tbody tr').count());
await page.keyboard.press('j');
check('j steps to the next protocol while open', (await text('.detail h2')) === 'Steakhouse Financial', await text('.detail h2'));
await page.locator('.detail .seg button', { hasText: '$25K' }).click();
check('deposit re-plans in place', (await text('.steps .sum')).includes('$25K'), await text('.steps .sum'));
await page.keyboard.press('Escape');
check('esc closes the detail', (await page.locator('.detail').count()) === 0);
await page.locator('.tools .seg button', { hasText: 'Farm' }).click();
const farms = await rows();
check('verdict filter narrows the board', farms > 0 && farms < 198, farms);
check('status line sums the filtered farms', /farming all \d+ at \$25K each nets/.test(await text('#status')), await text('#status'));
await page.keyboard.press('/'); await page.keyboard.type('solana');
const solana = await rows();
check('/ focuses search and it filters', solana > 0 && solana < farms, solana);
await page.locator('th', { hasText: 'TVL' }).click();
const first = await page.locator('#rows tbody tr td.num').first().innerText();
await page.locator('th', { hasText: 'TVL' }).click();
check('heading click sorts, second click reverses', first !== (await page.locator('#rows tbody tr td.num').first().innerText()));
await page.locator('[data-q]').fill('zzzz');
check('empty state offers a way out', (await text('.empty')).includes('Clear them'));
await page.locator('[data-reset]').click();
check('clear restores the board', (await rows()) === 198, await rows());
for (const [tab, n] of [['Already trade', 416], ['Set aside', 144]]) { await page.locator('.top nav button', { hasText: tab }).click(); const c = await page.locator('#rows tbody tr').count(); check(`${tab} lists ${n}`, c === n, c); }
await page.locator('.top nav button', { hasText: 'Model' }).click();
check('model page draws both fits', (await page.locator('.model svg').count()) === 2);
check('no page errors', errors.length === 0, errors);
await browser.close();
