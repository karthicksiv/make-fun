// QA only: the what-if row and the CSV export.
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
const { chromium } = createRequire(import.meta.url)('playwright');
const browser = await chromium.launch(), page = await browser.newPage({ viewport: { width: 1152, height: 720 }, acceptDownloads: true });
const errors = []; page.on('pageerror', (e) => errors.push(e.message));
await page.goto(pathToFileURL(process.argv[2]).href); await page.waitForSelector('#rows table');
const check = (name, ok, got) => console.log((ok ? 'PASS ' : 'FAIL ') + name + (ok ? '' : ` (got ${JSON.stringify(got)})`));
const farms = async () => Number((await page.locator('[data-set=verdict][data-v=Farm]').innerText()).replace(/\D/g, ''));
const base = await farms();
await page.locator('[data-set=hurdle][data-v="0"]').click(); const noHurdle = await farms();
check('T-bill yield 0% re-plans to more farms', noHurdle > base, [base, noHurdle]);
await page.locator('[data-set=hurdle][data-v="0.08"]').click(); const high = await farms();
check('T-bill yield 8% re-plans to fewer farms', high < base, [base, high]);
await page.locator('[data-set=hurdle][data-v="0.04"]').click();
await page.locator('[data-set=share][data-v="0.2"]').click(); const rich = await farms();
check('a 20% airdrop share re-plans to more farms', rich > base, [base, rich]);
await page.locator('[data-set=share][data-v="0.1"]').click();
check('defaults restore the board', (await farms()) === base, await farms());
await page.locator('[data-set=scope][data-v=watch]').click();
const [download] = await Promise.all([page.waitForEvent('download'), page.locator('[data-export]').click()]);
const csv = readFileSync(await download.path(), 'utf8').split('\n');
check('CSV export downloads the rows shown', csv.length === 41 && csv[0].startsWith('rank,rank_low,rank_high,slug,name') && download.suggestedFilename() === 'launch-radar-2026-11-14.csv', [csv.length, download.suggestedFilename()]);
check('CSV rows carry the plan', /,(Farm|Thin|Skip),-?\d/.test(csv[1]), csv[1]);
check('readout links open a farm', await (async () => { await page.locator('dd [data-open]').first().click(); return (await page.locator('.detail h2').count()) === 1; })());
await page.keyboard.press('Escape');
check('the not-ranked link opens the set-aside tab', await (async () => { await page.locator('dd .more').click(); return (await page.locator('#rows tbody tr').count()) === 144 && /never ranked/.test(await page.locator('.note').innerText()) && /^Bybit/.test(await page.locator('#rows tbody tr').first().innerText()); })(), await page.locator('#rows tbody tr').count());
await page.goto(page.url().split('#')[0] + '#'); await page.waitForSelector('#rows table');
check('every row shows its cost and its minutes', (await page.locator('#rows tbody tr .cost').count()) === 198 && /\$[\d.]+( fees)? · \d+ min/.test(await page.locator('#rows tbody tr .cost').first().innerText()), await page.locator('#rows tbody tr .cost').first().innerText());
check('the coverage meter has three parts', (await page.locator('.meter i').count()) === 3);
check('the evidence holds both fits and the tests', (await page.locator('.proof svg.chart').count()) === 2 && (await page.locator('.proof .tests tbody tr').count()) === 5);
check('no page errors', errors.length === 0, errors);
await browser.close();
